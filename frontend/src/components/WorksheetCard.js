import React, { useState, useEffect } from 'react';
import { View, Text, StyleSheet, TouchableOpacity, Alert, TextInput } from 'react-native';
import { Feather } from '@expo/vector-icons';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import * as Speech from 'expo-speech';

// Helper to map typed languages to BCP-47 codes and check RTL
const getLanguageData = (langName) => {
  if (!langName) return { code: 'en-US', isRTL: false };
  const l = langName.toLowerCase();
  
  const rtlLanguages = ['urdu', 'arabic', 'sindhi', 'pashto', 'farsi', 'persian'];
  const isRTL = rtlLanguages.some(rtl => l.includes(rtl));

  let code = 'en-US';
  if (l.includes('urdu')) code = 'ur-PK';
  else if (l.includes('arabic')) code = 'ar-SA';
  else if (l.includes('hindi')) code = 'hi-IN';
  else if (l.includes('spanish')) code = 'es-ES';
  else if (l.includes('pashto')) code = 'ps';
  else if (l.includes('sindhi')) code = 'sd';
  else if (l.includes('french')) code = 'fr-FR';

  return { code, isRTL };
};

const WorksheetCard = ({ worksheet, language = 'English' }) => {
  const [isSpeaking, setIsSpeaking] = useState(false);
  const [isEditing, setIsEditing] = useState(false);
  const [editableContent, setEditableContent] = useState(worksheet.content);

  const { code: langCode, isRTL } = getLanguageData(language);

  useEffect(() => {
    return () => {
      Speech.stop();
    };
  }, []);

  const exportPDF = async () => {
    try {
      const html = `
        <html dir="${isRTL ? 'rtl' : 'ltr'}">
          <head>
            <style>
              body { 
                font-family: 'Helvetica', sans-serif; 
                padding: 40px; 
                color: #1e293b;
              }
              h1 { color: #ff007f; text-align: center; margin-bottom: 30px; font-size: 28px; border-bottom: 2px solid #e2e8f0; padding-bottom: 10px; }
              .content { font-size: 16px; line-height: 1.8; white-space: pre-wrap; }
              .footer { margin-top: 50px; font-size: 12px; color: #94a3b8; text-align: center; }
            </style>
          </head>
          <body>
            <h1>${worksheet.grade_level} Worksheet</h1>
            <div class="content">${editableContent}</div>
            <div class="footer">Generated by EduNova AI Co-Teacher</div>
          </body>
        </html>
      `;
      const { uri } = await Print.printToFileAsync({ html });
      await Sharing.shareAsync(uri);
    } catch (err) {
      console.error("Failed to generate PDF", err);
    }
  };

  const toggleSpeech = async () => {
    if (isSpeaking) {
      Speech.stop();
      setIsSpeaking(false);
      return;
    }
    try {
      if (langCode === 'sd' || langCode === 'ps') {
        Alert.alert(
          "Limited Voice Support",
          `Your phone's native voice engine may not support ${language}.`
        );
      }
      setIsSpeaking(true);
      Speech.speak(editableContent, {
        language: langCode || undefined,
        onDone: () => setIsSpeaking(false),
        onStopped: () => setIsSpeaking(false),
        onError: () => {
          setIsSpeaking(false);
          Alert.alert("Voiceover Error", `Voice for ${language} might not be installed.`);
        }
      });
    } catch (e) {
      setIsSpeaking(false);
    }
  };

  return (
    <View style={styles.card}>
      <View style={styles.headerRow}>
        <Text style={styles.grade}>{worksheet.grade_level}</Text>
        <View style={styles.actionButtons}>
          <TouchableOpacity 
            style={[styles.btn, isEditing ? styles.btnActive : null]} 
            onPress={() => setIsEditing(!isEditing)}
          >
            <View style={{ flexDirection: 'row', alignItems: 'center' }}>
              <Feather name={isEditing ? "save" : "edit-2"} size={12} color={isEditing ? "#0ea5e9" : "#64748b"} style={{ marginRight: 4 }} />
              <Text style={[styles.btnText, isEditing ? styles.btnTextActive : null]}>
                {isEditing ? "Save" : "Edit"}
              </Text>
            </View>
          </TouchableOpacity>
          <TouchableOpacity 
            style={[styles.btn, isSpeaking ? styles.btnActiveSpeech : null]} 
            onPress={toggleSpeech}
          >
            <View style={{ flexDirection: 'row', alignItems: 'center' }}>
              <Feather name={isSpeaking ? "square" : "volume-2"} size={12} color={isSpeaking ? "#ff007f" : "#64748b"} style={{ marginRight: 4 }} />
              <Text style={[styles.btnText, isSpeaking ? styles.btnTextActiveSpeech : null]}>
                {isSpeaking ? "Stop" : "Read"}
              </Text>
            </View>
          </TouchableOpacity>
          <TouchableOpacity style={[styles.btn, styles.btnPrimary]} onPress={exportPDF}>
            <View style={{ flexDirection: 'row', alignItems: 'center' }}>
              <Feather name="file-text" size={12} color="#fff" style={{ marginRight: 4 }} />
              <Text style={styles.btnTextPrimary}>Export</Text>
            </View>
          </TouchableOpacity>
        </View>
      </View>
      
      {isEditing ? (
        <TextInput
          style={[styles.textInput, { textAlign: isRTL ? 'right' : 'left' }]}
          value={editableContent}
          onChangeText={setEditableContent}
          multiline
        />
      ) : (
        <View style={{ marginTop: 5 }}>
          {editableContent.split('\n').map((paragraph, index) => (
            <Text 
              key={index} 
              style={[
                styles.content, 
                { 
                  textAlign: isRTL ? 'right' : 'left',
                  marginBottom: paragraph.trim() === '' ? 5 : 12 
                }
              ]}
            >
              {paragraph}
            </Text>
          ))}
        </View>
      )}
    </View>
  );
};

const styles = StyleSheet.create({
  card: {
    backgroundColor: '#fff',
    padding: 20,
    borderRadius: 20,
    width: '100%',
  },
  headerRow: {
    flexDirection: 'row',
    justifyContent: 'space-between',
    alignItems: 'flex-start',
    marginBottom: 15,
    borderBottomWidth: 2,
    borderBottomColor: '#f1f5f9',
    paddingBottom: 15,
    flexWrap: 'wrap',
    gap: 10,
  },
  grade: {
    fontSize: 20,
    fontFamily: 'Poppins_900Black',
    color: '#0ea5e9',
    marginTop: 5,
  },
  actionButtons: {
    flexDirection: 'row',
    flexWrap: 'wrap',
    gap: 8,
  },
  btn: {
    backgroundColor: '#f8fafc',
    paddingHorizontal: 12,
    paddingVertical: 8,
    borderRadius: 12,
    borderWidth: 2,
    borderColor: '#e2e8f0',
  },
  btnText: {
    color: '#64748b',
    fontFamily: 'Poppins_700Bold',
    fontSize: 12,
  },
  btnActive: {
    backgroundColor: 'rgba(14, 165, 233, 0.1)',
    borderColor: '#0ea5e9',
  },
  btnTextActive: {
    color: '#0ea5e9',
  },
  btnActiveSpeech: {
    backgroundColor: 'rgba(255, 0, 127, 0.1)',
    borderColor: '#ff007f',
  },
  btnTextActiveSpeech: {
    color: '#ff007f',
  },
  btnPrimary: {
    backgroundColor: '#ff007f',
    borderColor: '#ff007f',
  },
  btnTextPrimary: {
    color: '#fff',
    fontFamily: 'Poppins_700Bold',
    fontSize: 12,
  },
  content: {
    fontSize: 16,
    color: '#1e293b',
    lineHeight: 28,
  },
  textInput: {
    fontSize: 16,
    color: '#1e293b',
    lineHeight: 28,
    backgroundColor: '#f8fafc',
    padding: 15,
    borderRadius: 12,
    borderWidth: 2,
    borderColor: '#e2e8f0',
    minHeight: 200,
    textAlignVertical: 'top',
  }
});

export default WorksheetCard;
